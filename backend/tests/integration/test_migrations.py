"""ADR-002 verification: migration round-trip, model/migration drift, FK and DDL semantics."""

from __future__ import annotations

import pytest
from alembic import command
from alembic.config import Config
from sqlalchemy import inspect, text

from app.db.session import (
    ForeignKeyViolationError,
    assert_no_fk_violations,
    create_app_engine,
    create_migration_engine,
)


def test_upgrade_downgrade_upgrade_round_trip(alembic_config: Config, database_url: str) -> None:
    command.upgrade(alembic_config, "head")
    command.downgrade(alembic_config, "base")
    command.upgrade(alembic_config, "head")

    engine = create_app_engine(database_url)
    try:
        assert "alembic_version" in inspect(engine).get_table_names()
    finally:
        engine.dispose()


def test_models_match_migrations(alembic_config: Config, migrated_db: str) -> None:
    # Raises AutogenerateDiffsDetected if ORM models and migration history disagree.
    command.check(alembic_config)


def test_app_engine_enforces_foreign_keys(database_url: str) -> None:
    engine = create_app_engine(database_url)
    try:
        with engine.connect() as conn:
            assert conn.exec_driver_sql("PRAGMA foreign_keys").scalar() == 1
    finally:
        engine.dispose()


def test_migration_engine_disables_foreign_keys(database_url: str) -> None:
    engine = create_migration_engine(database_url)
    try:
        with engine.connect() as conn:
            assert conn.exec_driver_sql("PRAGMA foreign_keys").scalar() == 0
    finally:
        engine.dispose()


def test_migration_engine_ddl_is_transactional(database_url: str) -> None:
    """Without the BEGIN recipe, pysqlite autocommits DDL and this table would survive."""
    engine = create_migration_engine(database_url)
    try:
        with pytest.raises(RuntimeError), engine.connect() as conn, conn.begin():
            conn.exec_driver_sql("CREATE TABLE should_vanish (id INTEGER PRIMARY KEY)")
            raise RuntimeError("simulated migration failure")
        assert "should_vanish" not in inspect(engine).get_table_names()
    finally:
        engine.dispose()


def test_fk_violation_check_rolls_back(database_url: str) -> None:
    """Orphan rows created while FKs are off are caught before commit."""
    engine = create_migration_engine(database_url)
    try:
        with engine.connect() as conn, conn.begin():
            conn.exec_driver_sql("CREATE TABLE parent (id INTEGER PRIMARY KEY)")
            conn.exec_driver_sql(
                "CREATE TABLE child (id INTEGER PRIMARY KEY, "
                "parent_id INTEGER REFERENCES parent(id))"
            )

        with pytest.raises(ForeignKeyViolationError), engine.connect() as conn, conn.begin():
            conn.exec_driver_sql("INSERT INTO child (id, parent_id) VALUES (1, 999)")
            assert_no_fk_violations(conn)

        with engine.connect() as conn:
            assert conn.execute(text("SELECT COUNT(*) FROM child")).scalar() == 0
    finally:
        engine.dispose()
